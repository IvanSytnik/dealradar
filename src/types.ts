import type { Lang } from "./i18n/index.js";
import type { MarketStats } from "./core/market.js";

/** A listing normalised across all marketplaces. */
export interface Listing {
  id: string;
  title: string;
  price: number | null;
  url: string;
  location: string;
  body: string;
  image: string | null;
  publishedAt: number | null;
}

/** What the user asked for, extracted from a search URL. */
export interface SearchQuery {
  site: string;
  url: string; // canonical, sorted by newest
  keyword: string; // human-readable query, may come from the category slug
  categoryHint: string | null;
  priceFrom: number | null;
  priceTo: number | null;
}

/**
 * Per-watch filter profile. Generated by AI from the query (or by a fallback),
 * editable by the user. Words, not regexes: safe to accept from an LLM.
 */
export interface FilterProfile {
  item: string; // what the user actually wants, e.g. "Xbox Series S console"
  mustAny: string[][]; // at least one group must fully match the title (all words of the group)
  exclude: string[]; // any match in title -> drop
  accessoryWords: string[]; // drop unless a bundle signal is present
  priceMin: number | null;
  priceMax: number | null;
  allowDefect: boolean;
  useAi: boolean;
  minScore: number; // 1-10
  /**
   * The AI's guess of the typical used price. Only a hint for the deal score, never a hard filter:
   * the guess varies between runs (480 / 560 / 600 € for the same PS5 search) and cut good listings.
   * Hard bounds (priceMin/priceMax) come from the user: the URL or /price.
   */
  typicalPrice?: { min: number | null; max: number | null } | null;
}

export interface AiVerdict {
  relevant: boolean;
  condition: "new" | "good" | "defect" | "unknown";
  bundle: string[];
  score: number;
  reason: string;
}

export type Plan = "free" | "pro";

export interface User {
  id: number; // telegram user id
  chatId: number;
  username: string | null;
  plan: Plan;
  /** Interface and AI-text language */
  lang: Lang;
  createdAt: number;
  blocked: boolean;
}

export interface Watch {
  id: number;
  userId: number;
  name: string;
  query: SearchQuery;
  profile: FilterProfile;
  intervalSec: number;
  active: boolean;
  seeded: boolean;
  failures: number;
  nextRunAt: number;
  lastRunAt: number | null;
  createdAt: number;
  /** Real market prices from the last /scan: feeds the deal score of live notifications. */
  market: MarketStats | null;
}
